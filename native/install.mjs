import { execFileSync } from 'node:child_process';
import { mkdirSync, cpSync, writeFileSync, chmodSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { homedir } from 'node:os';
import { fileURLToPath } from 'node:url';

const args = process.argv.slice(2);
const extensionId = args.length === 2 && args[0] === '--extension-id' ? args[1] : '';
if (!/^[a-p]{32}$/.test(extensionId)) throw new Error('用法：node native/install.mjs --extension-id <chrome://extensions 中的扩展 ID>');
if (process.platform !== 'darwin') throw new Error('当前安装器仅支持 macOS Google Chrome。');
if (Number(process.versions.node.split('.')[0]) < 20) throw new Error('需要 Node.js 20 或以上。');
process.umask(0o077);
const source = dirname(fileURLToPath(import.meta.url));
const root = join(homedir(), '.browser-skill/group-cleaner');
if (existsSync(join(root, 'job.lock'))) throw new Error('清理任务执行中，请完成后再安装。');
const app = join(root, 'app');
mkdirSync(app, { recursive: true, mode: 0o700 });
for (const name of ['host.mjs', 'worker.mjs', 'cleaner.mjs', 'backups.mjs', 'state.mjs', 'package.json', 'package-lock.json', 'vendor']) cpSync(join(source, name), join(app, name), { recursive: true });
execFileSync('npm', ['ci', '--omit=dev', '--no-audit', '--no-fund'], { cwd: app, stdio: 'inherit', env: { ...process.env, PATH: `${dirname(process.execPath)}:${process.env.PATH || ''}` } });
const backupDir = join(dirname(source), 'data/group-cleaner/backups');
mkdirSync(backupDir, { recursive: true, mode: 0o700 });
writeFileSync(join(root, 'config.json'), JSON.stringify({ extensionId, backupDir }), { mode: 0o600 });
const quote = (value) => `'${value.replaceAll("'", "'\\''")}'`;
const launcher = join(root, 'launch-host');
writeFileSync(launcher, `#!/bin/sh\nexec ${quote(process.execPath)} ${quote(join(app, 'host.mjs'))} "$@"\n`, { mode: 0o700 });
chmodSync(launcher, 0o700);
const hosts = join(homedir(), 'Library/Application Support/Google/Chrome/NativeMessagingHosts');
mkdirSync(hosts, { recursive: true, mode: 0o700 });
const manifest = join(hosts, 'com.cyh.browser_skill_group_cleaner.json');
writeFileSync(manifest, JSON.stringify({ name: 'com.cyh.browser_skill_group_cleaner', description: 'browser-skill saved tab group cleaner', path: launcher, type: 'stdio', allowed_origins: [`chrome-extension://${extensionId}/`] }, null, 2), { mode: 0o600 });
console.log(`本地清理组件已安装：${manifest}\n插件备份目录：${backupDir}\n请在 chrome://extensions 重新加载 browser-skill bridge，然后点击工具栏插件图标。`);
